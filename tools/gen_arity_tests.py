"""Writes the column-count tests: tests/test_arity.cpp and the compile_fail cases over the limit.

    python3 tools/gen_arity_tests.py

A set's columns are bits of one std::uint64_t (kMaxColumns in include/dreamor/index_set/plan.hpp),
so 63 columns is just under the limit, 64 is the limit itself, and 65 must stop on dreamor's own
message - directly, and when a 64-column set is spread into a new one. The files are written
out in full (64 column declarations, 64 arguments) and committed, so the test runner needs no
Python; edit this script, not its output, and re-run it.
"""

import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = (
    "// SPDX-License-Identifier: Apache-2.0\n"
    "// Generated by tools/gen_arity_tests.py - edit the script, not this file.\n"
)
SINGLE = 7  # every column but the first and the last holds this one value


def cols(n: int) -> list[str]:
    return [f"C{i}" for i in range(n)]


def key(n: int, first: int, last: int) -> str:
    """One full row as column values: first, SINGLE..., last."""
    values = [first] + [SINGLE] * (n - 2) + [last]
    return ", ".join(f"C{i}{{{v}}}" for i, v in enumerate(values))


def arity_block(n: int) -> str:
    c = cols(n)
    sources = ", ".join(["pair"] + ["single"] * (n - 2) + ["pair"])
    name = "x_" + "_".join(["1"] + [str(SINGLE)] * (n - 2) + ["0"])
    lines = [f"namespace arity{n} {{"]
    lines += [f'using C{i} = dreamor::Col<std::size_t, "c{i}">;' for i in range(n)]
    lines += [
        "",
        "static void check() {",
        "  const std::vector<std::size_t> pair{0, 1};",
        f"  const std::vector<std::size_t> single{{{SINGLE}}};",
        "  const IloEnv env;",
        # First and last columns from {0, 1}, the rest from one value: four rows, in nested-loop order.
        f"  const auto s = dreamor::makeSet<{', '.join(c)}>({sources}).collect();",
        "  DREAMOR_CHECK(s.size() == 4);",
        f"  DREAMOR_CHECK(std::get<C0>(*s.begin()).get() == 0 && std::get<C{n - 1}>(*s.begin()).get() == 0);",
        f"  DREAMOR_CHECK(std::get<C0>(*(s.begin() + 3)).get() == 1 && std::get<C{n - 1}>(*(s.begin() + 3)).get() == 1);",
        # where() reading the first and the last column, at build time and on the finished set.
        f"  const auto same = [](C0 a, C{n - 1} b) {{ return a.get() == b.get(); }};",
        f"  DREAMOR_CHECK(dreamor::makeSet<{', '.join(c)}>({sources}).where(same).collect().size() == 2);",
        "  DREAMOR_CHECK(s.where(same).size() == 2);",
        # select() keeps distinct rows: the two {0, 1} columns give four, a single-valued one gives one.
        f"  DREAMOR_CHECK((s.select<C0, C{n - 1}>().size() == 4) && (s.select<C1>().size() == 1));",
        # groupBy() / slice() on the first column.
        "  const auto byFirst = s.groupBy<C0>();",
        "  DREAMOR_CHECK(byFirst.size() == 2 && byFirst.slice(C0{1}).size() == 2);",
        # membership() with every column given.
        "  const auto inS = s.membership();",
        f"  DREAMOR_CHECK(inS({key(n, 1, 0)}) && !inS({key(n, 2, 0)}));",
        # ordered() over a projection.
        "  const auto firsts = s.select<C0>().ordered();",
        "  const auto* afterZero = firsts.next(C0{0});",
        "  DREAMOR_CHECK(afterZero != nullptr && std::get<C0>(*afterZero).get() == 1);",
        # A variable table on all of it: names, lookup by every column, a filtered sum.
        f'  const dreamor::concert::VarTable<{", ".join(c)}> x{{env, s, 0, 1, ILOFLOAT, "x"}};',
        f'  DREAMOR_CHECK(std::string{{x({key(n, 1, 0)}).getName()}} == "{name}");',
        f"  DREAMOR_CHECK(exactlyEqual(x({key(n, 1, 0)}).getUB(), 1));",
        "  IloExpr firstIsOne =",
        "      dreamor::concert::sumOf(env, s, x).where([](C0 a) { return a.get() == 1; }).build();",
        "  DREAMOR_CHECK(firstIsOne.expr_->terms.size() == 2);",
        "  firstIsOne.end();",
        "}",
        f"}}  // namespace arity{n}",
        "",
    ]
    return "\n".join(lines)


def test_arity() -> str:
    return (
        HEADER + "// A set of 63 columns (just under the limit) and of 64 (the limit itself) through everything\n"
        "// that works on whole rows.\n"
        "#include <cstddef>\n#include <string>\n#include <tuple>\n#include <vector>\n\n"
        "#include <ilcplex/ilocplex.h>\n\n"
        '#include "check.hpp"\n#include "dreamor/concert.hpp"\n#include "dreamor/index_set.hpp"\n'
        '#include "float_compare.hpp"\n\n'
        + arity_block(63)
        + "\n"
        + arity_block(64)
        + '\nint main() try {\n  arity63::check();\n  arity64::check();\n  return ::report("arity");\n'
        + "} catch (...) {\n  return ::uncaught();\n}\n"
    )


def compile_fail(n_direct: bool) -> str:
    c = cols(65)
    decls = "\n".join(f'using C{i} = dreamor::Col<std::size_t, "c{i}">;' for i in range(65))
    if n_direct:
        body = f"  (void)dreamor::makeSet<{', '.join(c)}>({', '.join(['I'] * 65)}).collect();"
    else:
        body = (
            f"  const auto s64 = dreamor::makeSet<{', '.join(c[:64])}>({', '.join(['I'] * 64)}).collect();\n"
            "  (void)dreamor::makeSet<C64>(s64, I).collect();"
        )
    what = "65 columns at once" if n_direct else "a 64-column set spread into a set with one more column"
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// expect: dreamor stops at 64\n"
        "// Generated by tools/gen_arity_tests.py - edit the script, not this file.\n"
        f"// {what}.\n"
        '#include "prelude.hpp"\n'
        f"{decls}\n"
        "int main() {\n"
        f"{body}\n"
        "}\n"
    )


outputs = {
    ROOT / "tests" / "test_arity.cpp": test_arity(),
    ROOT / "tests" / "compile_fail" / "makeset_too_many_columns.cpp": compile_fail(True),
    ROOT / "tests" / "compile_fail" / "makeset_too_many_columns_spread.cpp": compile_fail(False),
}
for path, text in outputs.items():
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")

# Formatted the way tools/format.sh would, so a regeneration leaves no diff.
clang_format = shutil.which("clang-format")
if clang_format:
    subprocess.run([clang_format, "-i", *map(str, outputs)], check=True)
else:
    print("clang-format not found: run tools/format.sh before committing")
