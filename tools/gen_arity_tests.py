"""Writes the compile_fail cases over the column limit.

    python3 tools/gen_arity_tests.py             # writes it
    python3 tools/gen_arity_tests.py --check     # fails if the file is not what it would write

A set's columns are bits of one std::uint64_t (kMaxColumns in include/dreamor/internal/index_set/plan.hpp),
so a 65th column must stop on dreamor's own message - directly, and when a 64-column set is spread
into a new one. Both cases are written out in full (65 column declarations, a chain of 65 steps) into one
topic file and committed, so building the tests does not run this script; edit this script, not its output,
and re-run it.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def cols(n: int) -> list[str]:
    return [f"C{i}" for i in range(n)]


def case(n_direct: bool) -> str:
    c = cols(65)
    decls = "\n".join(f"DREAMOR_VALUE_COLUMN(C{i}, std::size_t);" for i in range(65))

    def chain(columns: list[str]) -> str:
        return (
            "dreamor::index_set::relational::from<"
            + columns[0]
            + ">(I)"
            + "".join(f".cross<{x}>(I)" for x in columns[1:])
        )

    if n_direct:
        name = "set_too_many_columns"
        body = f"  (void){chain(c)}.build();"
    else:
        name = "set_too_many_columns_spread"
        body = f"  const auto s64 = {chain(c[:64])}.build();\n  (void)dreamor::index_set::relational::from(s64).cross<C64>(I).build();"

    what = "65 columns at once" if n_direct else "a 64-column set spread into a set with one more column"
    # The first case explains the message, for the Compile-time messages page (docs/dev/diagnostics.md); the blank line
    # ends the explanation before the case's own comment.
    explained = (
        "// when: A set of more than 64 columns, built at once or by spreading a set into a wider one.\n"
        "//\n"
        "// fix: Split it into sets that share key columns.\n"
        "\n"
        if n_direct
        else ""
    )
    return (
        f"#ifdef DREAMOR_CASE_{name}\n"
        "// expect: dreamor stops at 64\n"
        f"{explained}"
        f"// {what}.\n"
        f"{decls}\n"
        "int main() {\n"
        f"{body}\n"
        "}\n"
        f"#endif  // DREAMOR_CASE_{name}\n"
    )


PATH = ROOT / "tests" / "compile_fail" / "set_too_many_columns.cpp"
# REUSE-IgnoreStart
TEXT = (
    "// SPDX-License-Identifier: MPL-2.0\n"
    "// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was\n"
    "// not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.\n"
    "//\n"
    "// Code that must not compile: a set past 64 columns. Each case sits between `#ifdef DREAMOR_CASE_<name>` and\n"
    "// its `#endif` and is compiled alone (tests/cases.py). Generated by tools/gen_arity_tests.py - edit the\n"
    "// script, not this file.\n"
    '#include "prelude.hpp"\n'
    "\n" + case(True) + "\n" + case(False)
)
# REUSE-IgnoreEnd


def formatted() -> str:
    """The file as written: the text through the pinned clang-format, as tools/format.sh leaves it."""
    run = subprocess.run(
        [str(ROOT / "tools" / "clang-format"), f"--assume-filename={PATH}"],
        input=TEXT,
        capture_output=True,
        text=True,
        check=False,
    )
    if run.returncode != 0:
        sys.exit(f"tools/clang-format failed: {run.stderr}")
    return run.stdout


if "--check" in sys.argv[1:]:
    if PATH.read_text() != formatted():
        sys.exit(f"{PATH.relative_to(ROOT)} is not what tools/gen_arity_tests.py writes: run it")
else:
    PATH.write_text(formatted())
    print(f"wrote {PATH.relative_to(ROOT)}")
