"""Writing the reference: a page a section, an index, the gathered pages (compile-time messages, exceptions,
debug-build checks), each
signature through the pinned clang-format, and the site's nav.
"""

import re
import subprocess
import tempfile
from pathlib import Path

from refgen.common import ROOT, TITLE_ID, page_name
from refgen.entries import FIELDS, Contract, Entry, Reference, first_sentence
from refgen.messages import MessageSection

SIGNATURE_COLUMNS = 88
NAV_BEGIN = "    # The reference's pages, in tools/reference_sections.txt's order"
NAV_END = "    # (end of the reference's pages)"
GENERATED = "<!-- Generated by tools/gen_reference.py from the headers' /// comments: edit them, not this file. -->"
GENERATED_MESSAGES = (
    "<!-- Generated by tools/gen_reference.py from the compile_fail cases' expect, when and fix lines and the headers'"
    " /// comments: edit them, not this file. -->"
)
CHECKS_PAGE = "debug-build-checks.md"


def format_signatures(signatures: list[str]) -> list[str]:
    """The signatures through the pinned clang-format at SIGNATURE_COLUMNS; a macro's as it is."""
    code = [s for s in signatures if not s.startswith("#")]
    pieces = []
    if code:
        version = re.search(r"^CLANG_FORMAT_VERSION=(\S+)", (ROOT / "tools/format.sh").read_text(), re.M).group(1)
        style = re.sub(
            r"^ColumnLimit:.*$", f"ColumnLimit: {SIGNATURE_COLUMNS}", (ROOT / ".clang-format").read_text(), flags=re.M
        )
        source = "".join(f"// @@ {k}\n{s};\n" for k, s in enumerate(code))
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / ".clang-format").write_text(style)
            (Path(tmp) / "signatures.cpp").write_text(source)
            result = subprocess.run(
                ["uvx", "-q", f"clang-format@{version}", str(Path(tmp) / "signatures.cpp")],
                capture_output=True,
                text=True,
                check=True,
            )
        pieces = [p.rstrip().removesuffix(";") for p in re.split(r"^// @@ \d+\n", result.stdout, flags=re.M)[1:]]
    formatted = iter(pieces)
    return [s if s.startswith("#") else next(formatted) for s in signatures]


def render(reference: Reference) -> dict[str, str]:
    """The reference as pages, a section a page, and an index that lists them in order: {file name: text}."""
    entries = reference.all_entries()
    formatted = iter(format_signatures([s for e in entries for s in e.signatures]))
    for entry in entries:
        entry.signatures = [next(formatted) for _ in entry.signatures]
    contracts = reference.contracts

    def box(out: list[str], entry: Entry, level: int) -> None:
        short = entry.qualified.rsplit("::", 1)[-1]
        out.extend([f"{'#' * level} `{short}` {{#{entry.anchor}}}", ""])
        for one in [entry, *entry.overloads]:
            panel(out, one)
        for member in entry.members:
            box(out, member, level + 1)

    def panel(out: list[str], entry: Entry) -> None:
        out.extend([f'!!! abstract "`{entry.qualified}` - {entry.decl.kind}"', ""])
        content = (["```cpp", "\n\n".join(entry.signatures), "```", ""] if entry.signatures else []) + [
            entry.summary,
            "",
        ]
        for paragraph in entry.body:
            content += [paragraph, ""]
        for name in FIELDS:
            if name in entry.fields:
                text = entry.fields[name]
                if name == "Contract":
                    text = " ".join(
                        f"{first_sentence(contracts[c].sentence)} ([checked in a debug build]({CHECKS_PAGE}#{c}))"
                        if c in contracts
                        else c
                        for c in re.findall(r"\w+", text)
                    )
                content.append(f"- **{name}:** {text}")
        out.extend(("    " + line) if line else "" for line in "\n".join(content).rstrip().split("\n"))
        out.append("")

    pages = {}
    index = [GENERATED, "", f"# API reference {{#{TITLE_ID}}}", ""]
    for section in reference.sections:
        name = page_name(section.title)
        index.append(f"- [{section.title}]({name})")
        generated = GENERATED_MESSAGES if section.title == "Compile-time messages" else GENERATED
        out = [generated, "", f"# {section.title} {{#{TITLE_ID}}}", ""]
        for paragraph in section.intro:
            out += [paragraph, ""]
        if section.guide:
            out += [f"In use: [the guide](../{section.guide}).", ""]
        if section.title == "Compile-time messages":
            out += messages(reference.messages)
        elif section.title == "Exceptions":
            out += exceptions(entries)
        elif section.title == "Debug-build checks":
            out += checks(contracts)
        for entry in section.entries:
            box(out, entry, 2)
        pages[name] = "\n".join(out).rstrip() + "\n"
    pages["index.md"] = "\n".join(index) + "\n"
    return pages


def messages(sections: list[MessageSection]) -> list[str]:
    """A heading a section and, under it, a heading a message - its words, as a compiler gives them, so that a search
    for an error finds it - with when it comes, what to write instead, and the cases that pin it; then the cases that C++
    itself rejects, each with when and what to write instead."""
    out, taken = [], set()
    for section in sections:
        out += [f"## {section.title} {{#{slug(section.title, taken)}}}", ""]
        for message in section.messages:
            if message.text is None:
                continue
            out += [f"### `{message.text}` {{#{slug(message.text, taken)}}}", ""]
            out += [f"- **Message:** {code(sentence)}" for sentence in message.sentences]
            out += [f"- **When:** {message.when}", f"- **Fix:** {message.fix}"]
            out += ["- **Cases:** " + ", ".join(f"`{case_name(c)}`" for c in message.cases), ""]
        rejected = [m for m in section.messages if m.text is None]
        if rejected:
            out += ["C++ itself rejects these, with an error of its own:", ""]
            out += [f"- {m.when} {m.fix} (`{case_name(m.cases[0])}`)" for m in rejected]
            out.append("")
    return out


def code(text: str) -> str:
    """Text as inline code, its delimiter one backtick longer than the longest run of backticks inside it."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * (longest + 1)
    pad = " " if longest else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def slug(text: str, taken: set[str]) -> str:
    """A heading's id: its first eight words, in lower case, joined by hyphens, and a number after it where an earlier
    heading of the page has those words."""
    base = "-".join(re.findall(r"[a-z0-9]+", text.lower())[:8]) or "message"
    anchor, n = base, 2
    while anchor in taken:
        anchor, n = f"{base}-{n}", n + 1
    taken.add(anchor)
    return anchor


def case_name(case) -> str:
    """A case's name as the CTest test names it: its folder, then its name."""
    return f"{case.path.parent.relative_to(ROOT / 'tests').as_posix()}/{case.name}"


def exceptions(entries: list[Entry]) -> list[str]:
    """Every exception a Throws field names - each clause starts with its type in backticks - a heading a type, and under
    it each entry that throws it, with the rest of its clause: when."""
    thrown: dict[str, list[str]] = {}
    for entry in entries:
        for clause in entry.fields.get("Throws", "").split(";"):
            match = re.match(r"\s*`([\w:]+)`(.*)", clause, re.S)
            if match:
                when = match.group(2).strip().rstrip(".")
                when = f" {when}" if when and not when.startswith(",") else when
                thrown.setdefault(match.group(1), []).append(f"- `{entry.qualified}`{when}.")
    out = []
    for name in sorted(thrown):
        out += [f"## `{name}` {{#{re.sub(r'[^\w-]', '', name.lower())}}}", "", *thrown[name], ""]
    return out


def checks(contracts: dict[str, Contract]) -> list[str]:
    """A heading a contract, its name the anchor an entry's Contract field links to: its sentence, the entries that
    name it, what its debug check prints, and the cases that break it."""
    out = []
    for contract in sorted(contracts.values(), key=lambda c: c.name):
        out += [f"## {contract.name} {{#{contract.name}}}", "", contract.sentence, ""]
        out.append("- **Named by:** " + (", ".join(f"`{q}`" for q in contract.named_by) or "no entry"))
        if contract.cases:
            stops = sorted({expect for _, expect, _ in contract.cases})
            out.append("- **A debug build stops with:** " + "; ".join(f"`{expect}`" for expect in stops))
            out.append("- **Cases:** " + ", ".join(f"`{name}` ({path})" for name, _, path in contract.cases))
        else:
            out.append("- **Unchecked:** no case breaks it.")
        out.append("")
    return out


def with_nav(config: str, pages: dict[str, str]) -> str:
    """The site's configuration with the reference's pages in its nav, index.md first: the lines between the comment
    that starts with NAV_BEGIN (two lines) and NAV_END."""
    lines = config.split("\n")
    begin = next(k for k, line in enumerate(lines) if line.startswith(NAV_BEGIN)) + 2
    end = lines.index(NAV_END)
    names = ["index.md", *(name for name in pages if name != "index.md")]
    return "\n".join([*lines[:begin], *(f'    "reference/{name}",' for name in names), *lines[end:]])
